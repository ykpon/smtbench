#include "textflag.h"

// func avxLoop(n int, acc *[64]float32, c *[16]float32)
// 8 independent YMM chains: acc = acc*c[0:8] + c[8:16], n times.
TEXT ·avxLoop(SB), NOSPLIT, $0-24
	MOVQ n+0(FP), CX
	MOVQ acc+8(FP), AX
	MOVQ c+16(FP), BX
	VMOVUPS 0(AX), Y0
	VMOVUPS 32(AX), Y1
	VMOVUPS 64(AX), Y2
	VMOVUPS 96(AX), Y3
	VMOVUPS 128(AX), Y4
	VMOVUPS 160(AX), Y5
	VMOVUPS 192(AX), Y6
	VMOVUPS 224(AX), Y7
	VMOVUPS 0(BX), Y8
	VMOVUPS 32(BX), Y9
	TESTQ CX, CX
	JZ done

loop:
	VMULPS Y8, Y0, Y0
	VMULPS Y8, Y1, Y1
	VMULPS Y8, Y2, Y2
	VMULPS Y8, Y3, Y3
	VMULPS Y8, Y4, Y4
	VMULPS Y8, Y5, Y5
	VMULPS Y8, Y6, Y6
	VMULPS Y8, Y7, Y7
	VADDPS Y9, Y0, Y0
	VADDPS Y9, Y1, Y1
	VADDPS Y9, Y2, Y2
	VADDPS Y9, Y3, Y3
	VADDPS Y9, Y4, Y4
	VADDPS Y9, Y5, Y5
	VADDPS Y9, Y6, Y6
	VADDPS Y9, Y7, Y7
	DECQ CX
	JNZ loop

done:
	VMOVUPS Y0, 0(AX)
	VMOVUPS Y1, 32(AX)
	VMOVUPS Y2, 64(AX)
	VMOVUPS Y3, 96(AX)
	VMOVUPS Y4, 128(AX)
	VMOVUPS Y5, 160(AX)
	VMOVUPS Y6, 192(AX)
	VMOVUPS Y7, 224(AX)
	VZEROUPPER
	RET
